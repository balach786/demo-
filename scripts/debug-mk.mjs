import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
page.on('console', m => { if (m.type() === 'error') console.log('CONSOLE-ERR:', m.text()); });
page.on('pageerror', e => console.log('PAGEERROR:', e.message));
await page.goto('http://localhost:5173', { waitUntil: 'networkidle' });
await page.click('.nav-item:has-text("Transactions")');
await page.waitForTimeout(400);
const mk = async (type, { amount, desc, mode, party, exp } = {}) => {
  await page.click('button:has-text("Add Transaction")');
  await page.waitForTimeout(250);
  await page.selectOption('#f-type', type);
  if (mode && ['sale', 'purchase', 'receipt', 'payment'].includes(type)) await page.selectOption('#f-mode', mode);
  if (party) await page.selectOption('#f-party', party);
  if (exp) await page.selectOption('#f-exp', exp);
  await page.fill('#f-amount', String(amount));
  await page.fill('#f-desc', desc);
  await page.click('button:has-text("Post to Demo Ledger")');
  await page.waitForTimeout(650);
  const errs = await page.locator('.field-error').allInnerTexts();
  const toast = await page.locator('.toast-success').allInnerTexts();
  console.log(type, '→ field-errors:', JSON.stringify(errs), '| success toast:', toast.length ? 'YES' : 'no');
  if (errs.length || !toast.length) await page.keyboard.press('Escape');
  else await page.waitForTimeout(200);
};
await mk('receipt', { amount: 50000, desc: 'DBG Money Received — Ahmed Enterprises', mode: 'bank', party: 'ahmed' });
await mk('payment', { amount: 30000, desc: 'DBG Money Paid — ABC Traders', mode: 'bank', party: 'abct' });
await mk('sale', { amount: 120000, desc: 'DBG Sales — credit to Raza Cloth House', mode: 'credit', party: 'raza' });
await mk('purchase', { amount: 90000, desc: 'DBG Purchases — credit from XYZ Distributors', mode: 'credit', party: 'xyz' });
await mk('expense', { amount: 7500, desc: 'DBG Expenses — transport voucher', exp: 'transport' });
await mk('deposit', { amount: 25000, desc: 'DBG Cash Deposit — to HBL' });
await mk('withdrawal', { amount: 15000, desc: 'DBG Cash Withdrawal — from HBL' });
await mk('transfer', { amount: 40000, desc: 'DBG Bank Transfer — HBL to Meezan' });
const extras = await page.evaluate(() => JSON.parse(localStorage.getItem('abs-demo-state-v1')).extraTransactions.map(t => t.type));
console.log('posted extras:', JSON.stringify(extras));
await browser.close();
