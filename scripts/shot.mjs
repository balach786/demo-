import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1560, height: 940 } });
await page.goto('http://localhost:5173', { waitUntil: 'networkidle' });
await page.waitForTimeout(700);
await page.screenshot({ path: 'docs/qa/01-dashboard.png', fullPage: true });
await page.click('.nav-item:has-text("Approvals")');
await page.waitForTimeout(400);
await page.screenshot({ path: 'docs/qa/03a-approvals-pending.png', fullPage: false });
await page.click('.nav-item:has-text("Parties")');
await page.waitForTimeout(400);
await page.screenshot({ path: 'docs/qa/08-parties.png', fullPage: true });
await page.click('.nav-item:has-text("Documents")');
await page.waitForTimeout(400);
await page.screenshot({ path: 'docs/qa/09-documents.png', fullPage: true });
await page.click('.nav-item:has-text("Bank Accounts")');
await page.waitForTimeout(400);
await page.screenshot({ path: 'docs/qa/10-banks.png', fullPage: true });
await browser.close();
